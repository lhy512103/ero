#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Draws the two shared chemical-fluid textures (stage 2 M1).

    python tools/art/m1_fluids.py [repo root]

Every chemical fluid renders with these greyscale frames and is tinted per fluid by the client, so
one still and one flowing animation cover all of them. The frames are generated from a fixed seed.

The look follows vanilla water: 16x16 frames, a soft rolling swell rather than noise, and a few
bright crests along the ridges. Vanilla's own still water is a handful of hand-placed bands; here the
same bands are generated by sampling a smooth wave field, so the texture has no salt-and-pepper
speckle when it is stretched over a tank face or a pipe window.
"""
import math
import os
import random
import struct
import sys
import zlib

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else
                       os.path.join(os.path.dirname(__file__), "..", "..")).replace("\\", "/")
TEX = ROOT + "/src/main/resources/assets/iuce/textures/block/"
FRAMES = 32
SIZE = 16

# Tone ramp, dark to bright. Vanilla water sits between about 0.55 and 1.0 brightness; staying in that
# band keeps a tinted fluid readable instead of washing out to the tint colour itself.
RAMP = [176, 192, 206, 219, 231, 240, 248, 255]


def chunk(tag, data):
    return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)


def save(name, frames, frametime):
    lines = []
    for frame in frames:
        for row in frame:
            lines.append(b"\x00" + b"".join(bytes((value, value, value, 255)) for value in row))
    raw = b"".join(lines)
    width, height = SIZE, SIZE * len(frames)
    document = (b"\x89PNG\r\n\x1a\n"
                + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
                + chunk(b"IDAT", zlib.compress(raw, 9))
                + chunk(b"IEND", b""))
    with open(TEX + name + ".png", "wb") as handle:
        handle.write(document)


def tone(value):
    """A 0..1 height squeezed into one of the ramp's steps."""
    index = max(0, min(len(RAMP) - 1, int(value * (len(RAMP) - 1) + 0.5)))
    return RAMP[index]


def wave(x, y, t, scale, phase):
    """One smooth circle-ish wave; no diagonal stripe, so it reads as rolling water."""
    return math.sin(x * scale + t + phase) * math.cos(y * scale * 0.8 - t * 0.35 + phase)


def still_frame(frame):
    t = frame / FRAMES * 2 * math.pi
    rows = []
    for y in range(SIZE):
        row = []
        for x in range(SIZE):
            # A broad diagonal swell with two slow cross-waves over it, all wrapped so the tile
            # repeats without a seam; the crest of the swell is lifted into a bright ridge.
            u, v = (x + 0.5) / SIZE * 2 * math.pi, (y + 0.5) / SIZE * 2 * math.pi
            swell = math.sin(u + v * 2 + t)
            cross = math.sin(u * 2 - v + t * 0.5) * 0.35
            ripple = math.sin(u * 3 + v * 3 - t * 2) * 0.15
            height = swell * 0.5 + cross + ripple
            level = 0.5 + 0.42 * height
            if swell > 0.75:
                level = min(1.0, level + 0.18)  # the crests catch the light, as on vanilla water
            row.append(tone(level))
        rows.append(row)
    return rows


def flow_frame(frame):
    t = frame / FRAMES * 2 * math.pi
    rows = []
    for y in range(SIZE):
        row = []
        for x in range(SIZE):
            u, v = (x + 0.5) / SIZE * 2 * math.pi, (y + 0.5) / SIZE * 2 * math.pi
            # Running water: long bands travelling along one axis, with a slower cross-wave bending
            # them so they read as current rather than as stripes.
            band = math.sin(v * 2 - t * 2 + math.sin(u * 0.8 + t * 0.4) * 0.9)
            ripple = math.sin(v * 4 + u + t * 3) * 0.28
            lean = math.sin(u - t) * 0.22
            level = 0.47 + 0.36 * (band + ripple + lean)
            if band > 0.8:
                level = min(1.0, level + 0.16)
            row.append(tone(level))
        rows.append(row)
    return rows


def main():
    save("chemical_still", [still_frame(f) for f in range(FRAMES)], 8)
    save("chemical_flow", [flow_frame(f) for f in range(FRAMES // 2)], 4)
    print("wrote chemical_still and chemical_flow")


main()
